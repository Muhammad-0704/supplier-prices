function rng(seed: number) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function uuid(r: () => number): string {
  const h = Array.from({ length: 32 }, () => Math.floor(r() * 16).toString(16)).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

/** Дата 1С без пояса, московское время */
function onecDate(t: number): string {
  return new Date(t + 3 * 3600_000).toISOString().slice(0, 19);
}

export interface MockBase {
  items: ODataRow[];
  units: ODataRow[];
  suppliers: ODataRow[];
  receipts: ODataRow[];
}

export function buildMockBase(now = Date.now()): MockBase {
  const r = rng(20261025);
  const DAY = 86_400_000;
  const day0 = Math.floor(now / DAY) * DAY + 9 * 3600_000; // утро сегодняшнего дня

  const unitRefs = new Map<string, string>();
  const units: ODataRow[] = [];
  const unitRef = (name: string) => {
    if (!unitRefs.has(name)) {
      const ref = uuid(r);
      unitRefs.set(name, ref);
      units.push({ Ref_Key: ref, Description: name, DeletionMark: false });
    }
    return unitRefs.get(name)!;
  };

  const items: ODataRow[] = [];
  const catalog: { ref: string; cat: number; base: number }[] = [];
  CATS.forEach(([cat, list], ci) => {
    const folder = uuid(r);
    items.push({ Ref_Key: folder, Description: cat, IsFolder: true, Parent_Key: '00000000-0000-0000-0000-000000000000', DeletionMark: false });
    for (const line of list.split(';')) {
      const [name, unit, base] = line.split('|');
      const ref = uuid(r);
      items.push({ Ref_Key: ref, Description: name, IsFolder: false, Parent_Key: folder, DeletionMark: false, ЕдиницаИзмерения_Key: unitRef(unit) });
      catalog.push({ ref, cat: ci, base: Number(base) });
    }
  });

  const suppliers: ODataRow[] = SUPPLIERS.map(([name]) => ({
    Ref_Key: uuid(r), Description: name, IsFolder: false, DeletionMark: false, ИНН: String(7700000000 + Math.floor(r() * 99999999)),
  }));
  const general = SUPPLIERS.length - 1;

  // Каждая закупка — отдельная накладная с одной-несколькими строками; группируем по поставщику и дню
  const docs = new Map<string, ODataRow & { Запасы: ODataRow[] }>();
  let docNo = 1000;
  for (const it of catalog) {
    const spec = SUPPLIERS.map((s, i) => [s, i] as const).filter(([s, i]) => i !== general && s[1].includes(it.cat)).map(([, i]) => i);
    for (let i = spec.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [spec[i], spec[j]] = [spec[j], spec[i]]; }
    const chosen = spec.slice(0, Math.min(spec.length, 2 + Math.floor(r() * 3)));
    if (chosen.length < 2 || r() < 0.5) chosen.push(general);
    const rare = r() < 0.27;
    for (const si of chosen) {
      const f = si === general ? 1.04 + r() * 0.12 : 0.88 + r() * 0.22;
      const n = rare ? 2 + Math.floor(r() * 3) : 3 + Math.floor(r() * 5);
      const lastAgo = Math.floor(Math.pow(r(), 2.2) * (rare ? 95 : 55)) + (rare ? 34 + Math.floor(r() * 50) : 0);
      const agos: number[] = [];
      for (let j = 0, d = lastAgo; j < n; j++) { agos.unshift(d); d += (rare ? 25 : 8) + Math.floor(r() * 24); }
      let p = it.base * f * (0.93 + r() * 0.04);
      agos.forEach((ago, j) => {
        if (j > 0) p *= 1 + (r() - 0.38) * 0.07;
        const price = p >= 1000 ? Math.round(p / 10) * 10 : Math.max(1, Math.round(p));
        const key = `${si}:${ago}`;
        if (!docs.has(key)) {
          docs.set(key, {
            Ref_Key: uuid(r), Number: `ПН-${String(++docNo).padStart(6, '0')}`, Date: onecDate(day0 - ago * DAY),
            Posted: true, DeletionMark: false, Контрагент_Key: suppliers[si].Ref_Key as string, Запасы: [],
          });
        }
        const doc = docs.get(key)!;
        doc.Запасы.push({ LineNumber: doc.Запасы.length + 1, Номенклатура_Key: it.ref, Количество: 1 + Math.floor(r() * (rare ? 4 : 14)), Цена: price });
      });
    }
  }
  return { items, units, suppliers, receipts: [...docs.values()] };
}

let cached: { day: number; base: MockBase } | null = null;
function base(): MockBase {
  const day = Math.floor(Date.now() / 86_400_000);
  if (!cached || cached.day !== day) cached = { day, base: buildMockBase() };
  return cached.base;
}

/** fetch-совместимая функция, которая отвечает как OData 1С:Фреш. */
export const mockFetcher: Fetcher = async (url) => {
  const u = new URL(url);
  const entity = decodeURIComponent(u.pathname.split('/').pop() || '');
  const b = base();
  let rows: ODataRow[] =
    entity === 'Catalog_Номенклатура' ? b.items :
    entity === 'Catalog_КлассификаторЕдиницИзмерения' ? b.units :
    entity === 'Catalog_Контрагенты' ? b.suppliers :
    entity === 'Document_ПриходнаяНакладная' ? b.receipts :
    entity === 'Document_ПриходнаяНакладная_Запасы' ? b.receipts.flatMap((d) => (d.Запасы as ODataRow[]).map((l) => ({ Ref_Key: d.Ref_Key, ...l }))) : [];
  if (!rows.length && !entity.startsWith('Document_ПриходнаяНакладная')) {
    return new Response('Not found', { status: 404 });
  }
  const filter = u.searchParams.get('$filter') || '';
  const guids = [...filter.matchAll(/Ref_Key eq guid'([^']+)'/g)].map((m) => m[1]);
  if (guids.length) rows = rows.filter((r) => guids.includes(String(r.Ref_Key)));
  // Как настоящая 1С: при $select без табличной части строк в шапке нет
  const select = u.searchParams.get('$select');
  if (select && entity === 'Document_ПриходнаяНакладная' && !select.split(',').includes('Запасы')) {
    rows = rows.map(({ Запасы: _omit, ...rest }) => rest);
  }
  const m = /Date ge datetime'([^']+)'/.exec(filter);
  if (m) rows = rows.filter((d) => String(d.Date) >= m[1]);
  rows = [...rows].sort((a, z) => String(a.Ref_Key).localeCompare(String(z.Ref_Key)));
  const skip = Number(u.searchParams.get('$skip') || 0);
  const top = Number(u.searchParams.get('$top') || rows.length);
  return new Response(JSON.stringify({ 'odata.metadata': 'mock', value: rows.slice(skip, skip + top) }), {
    status: 200, headers: { 'Content-Type': 'application/json' },
  });
};
